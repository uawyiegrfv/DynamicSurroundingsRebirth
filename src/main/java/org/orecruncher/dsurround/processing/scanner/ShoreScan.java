    /**
     * Walks the window once. About six block reads per column, ~6.5k for the
     * default window - the same order as {@link FoliageScan}, which is why the
     * caller throttles this and reuses the result.
     */
    public static Grid scan(final Level level, final int cx, final int cz) {
        final long mark = System.nanoTime();
        final int size = RANGE * 2 + 1;
        final int ox = cx - RANGE;
        final int oz = cz - RANGE;
        final int waterTop = level.getSeaLevel() - 1;
        final Grid g = new Grid(ox, oz, size, waterTop);

        final BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos(0, 0, 0);
        for (int z = oz; z < oz + size; z++)
            for (int x = ox; x < ox + size; x++)
                classify(level, g, x, z, waterTop, p);

        collectRuns(g);

        g.scanNanos = System.nanoTime() - mark;
        return g;
    }

    /**
     * Every beach run in a classified grid: the cell census, then one pass per inland
     * direction. Split out of {@link #scan} so the offline simulator can drive the real
     * collection instead of a copy of it - a harness that re-implements this is a
     * harness that can disagree with the game, which is exactly how the joints were
     * measured as correct while the screen showed them wrong.
     *
     * <p>Needs no {@link Level}: everything here reads {@link Grid#cls}.</p>
     */
    static void collectRuns(final Grid g) {
        final int size = g.size;
        final int ox = g.ox;
        final int oz = g.oz;
        for (int i = 0; i < g.cls.length; i++) {
            switch (g.cls[i]) {
                case CLS_SEA -> g.seaCells++;
                case CLS_BEACH -> g.beachCells++;
                case CLS_HIGH -> g.highCells++;
                default -> g.unknownCells++;
            }
        }

        for (int di = 0; di < 4; di++) {
            final int dx = DIR_X[di];
            final int dz = DIR_Z[di];
            // The shore axis is whichever axis D is not on.
            final int ux = dx == 0 ? 1 : 0;
            final int uz = dx == 0 ? 0 : 1;
            for (int a = 0; a < size; a++) {
                int start = -1;
                for (int b = 0; b <= size; b++) {
                    boolean ok = false;
                    if (b < size) {
                        final int gx = ux == 1 ? b : a;
                        final int gz = uz == 1 ? b : a;
                        final int nx = gx + dx;
                        final int nz = gz + dz;
                        if (nx >= 0 && nx < size && nz >= 0 && nz < size)
                            ok = g.cls[gz * size + gx] == CLS_SEA
                                    && g.cls[nz * size + nx] != CLS_SEA;
                    }
                    if (ok) {
                        if (start < 0)
                            start = b;
                    } else if (start >= 0) {
                        final int gx0 = ux == 1 ? start : a;
                        final int gz0 = uz == 1 ? start : a;
                        addRun(g, ox + gx0, oz + gz0, ux, uz, dx, dz, b - start);
                        start = -1;
                    }
                }
            }
        }
    }

