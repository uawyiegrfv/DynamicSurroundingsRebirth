    /**
     * A frozen picture of the shoreline under the player. Runs depend only on
     * terrain (never on the swell), which is what lets the swell be recomputed
     * every tick without touching a single block again.
     */
    public static final class Grid {
        public final int ox, oz, size, waterTop;
        public final byte[] cls;
        public final ObjectArray<Run> runs = new ObjectArray<>();

        /** Scratch, reused by every {@link #build}: run-up water, then the foam line. */
        final byte[] filled;
        /**
         * Scratch: how much of each {@code filled} cell the front actually
         * covers, 0..1. Everything behind the front is 1; the one row of cells
         * the front is crossing is somewhere in between, and its quads are
         * faded in by exactly that fraction.
         */
        final float[] cov;
        final byte[] ftype;
        /** Straight: the single dry direction bit. Corner: the land corner index. */
        final byte[] fdir;
        /** Scratch: which cells the film already covered, so rects cannot overlap. */
        final byte[] used;
        /** Scratch: the coast as cell edges, each with its own beach depth. */
        ShoreEdge[] shoreEdges = new ShoreEdge[0];
        public int shoreEdgeCount;
        /** True when the window's main direction runs along X. */
        boolean mainAlongX = true;
        /** Diagnostics: coast edges by orientation, and the id/shuffle of the build. */
        public int edgeX, edgeZ;
        /** Diagnostics: identity of the grid the build actually used, and how many edges it collected. */
        public int gridId;
        public int shuffle;

        /**
         * Joints, counted and sampled. The maintainer can see the joints on screen but
         * reports "some that should be there are not, and every one that is there is in
         * the wrong place, always the same way" - which no offline harness has reproduced
         * (six synthetic coasts all place every joint exactly on the two bands it is
         * meant to bridge, distance 0). Rather than guess again, the first few joints are
         * written down verbatim so a log line can be compared against the screen.
         * Read-only: nothing here changes what is drawn.
         */
        public int jointEmitted, jointSplit, jointNoBandA, jointNoBandB, jointSameLine, jointFlat;
        /** Up to {@link #JOINT_SAMPLE} joints: cross edge, band corners, resulting ends. */
        public static final int JOINT_SAMPLE = 4;
        public final int[] jointInts = new int[JOINT_SAMPLE * 8];
        public final float[] jointFloats = new float[JOINT_SAMPLE * 4];
        public int jointSampleCount;

        public int runCells = 0;
        public int foamCells = 0;
        public int filmQuads = 0;
        public long scanNanos = 0L;
        /** Terrain tally from the last scan - what the predicates actually said. */
        public int seaCells = 0;
        public int beachCells = 0;
        public int highCells = 0;
        public int unknownCells = 0;
        public int runsDroppedByBiome = 0;
        /**
         * UV density tally: texels of texture laid along the foam line, against
         * the blocks of foam line they were laid along. Read off the quads the
         * emitters actually produced, so the diagnostics line cannot disagree
         * with the geometry - see {@link #STRIP_TEX_WIDTH}.
         */
        public float lineTexels = 0F;
        public float lineBlocks = 0F;
        /** Same tally for the film, which is a merged rectangle rather than a line. */
        public float filmTexels = 0F;
        public float filmBlocks = 0F;
        /** Quad tally from the last build, split by type. */
        public int stripQuads = 0;
        public int capQuads = 0;
        public int cornerQuads = 0;
        public int filledCells = 0;

        Grid(final int ox, final int oz, final int size, final int waterTop) {
            this.ox = ox;
            this.oz = oz;
            this.size = size;
            this.waterTop = waterTop;
            final int n = size * size;
            this.cls = new byte[n];
            this.filled = new byte[n];
            this.cov = new float[n];
            this.ftype = new byte[n];
            this.fdir = new byte[n];
            this.used = new byte[n];
        }

        public int idx(final int x, final int z) {
            return (z - this.oz) * this.size + (x - this.ox);
        }

        public boolean inGrid(final int x, final int z) {
            return x >= this.ox && x < this.ox + this.size
                    && z >= this.oz && z < this.oz + this.size;
        }

        /** True for cells far enough inside the window to be drawn. */
        public boolean inRenderArea(final int x, final int z) {
            final int gx = x - this.ox;
            final int gz = z - this.oz;
            return gx >= RENDER_MARGIN && gx <= this.size - 1 - RENDER_MARGIN
                    && gz >= RENDER_MARGIN && gz <= this.size - 1 - RENDER_MARGIN;
        }
    }

    /**
     * One straight piece of coast: {@code len} sea cells in a row along
     * {@code (ux,uz)}, each with dry land one step inland at {@code (dx,dz)}.
     * A headland cell appears in two runs - that is the corner, handled later.
     */
    public static final class Run {
        public final int startX, startZ;
        public final int ux, uz;
        public final int dx, dz;
        public final int len;
        /** Beach depth inland of each cell. */
        public final short[] d;
        /** 1 when the depth walk stopped on a {@link #CLS_HIGH} column. */
        public final byte[] stopHigh;
        /**
         * Scratch: run-up per cell for the current swell, <b>in blocks, not
         * cells</b>. It stays fractional on purpose - see {@link #build}. Once
         * it is rounded to whole cells the whole picture advances one block at a
         * time, which is not "steppy animation": it is the entire line jumping.
         */
        public final float[] f;

        Run(final int startX, final int startZ, final int ux, final int uz,
            final int dx, final int dz, final int len,
            final short[] d, final byte[] stopHigh) {
            this.startX = startX;
            this.startZ = startZ;
            this.ux = ux;
            this.uz = uz;
            this.dx = dx;
            this.dz = dz;
            this.len = len;
            this.d = d;
            this.stopHigh = stopHigh;
            this.f = new float[len];
        }
    }

    /**
     * Walks the window once. About six block reads per column, ~6.5k for the
     * default window - the same order as {@link FoliageScan}, which is why the
     * caller throttles this and reuses the result.
     */
    public static Grid scan(final Level level, final int cx, final int cz) {
        final long mark = System.nanoTime();
        final int size = RANGE * 2 + 1;
        final int ox = cx - RANGE;
        final int oz = cz - RANGE;
        final int waterTop = level.getSeaLevel() - 1;
        final Grid g = new Grid(ox, oz, size, waterTop);

        final BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos(0, 0, 0);
        for (int z = oz; z < oz + size; z++)
            for (int x = ox; x < ox + size; x++)
                g.cls[g.idx(x, z)] = classify(level, x, z, waterTop, p);

        collectRuns(g);

        g.scanNanos = System.nanoTime() - mark;
        return g;
    }

    /**
     * Every beach run in a classified grid: the cell census, then one pass per inland
     * direction. Split out of {@link #scan} so the offline simulator can drive the real
     * collection instead of a copy of it - a harness that re-implements this is a
     * harness that can disagree with the game, which is exactly how the joints were
     * measured as correct while the screen showed them wrong.
     *
     * <p>Needs no {@link Level}: everything here reads {@link Grid#cls}.</p>
     */
    static void collectRuns(final Grid g) {
        final int size = g.size;
        final int ox = g.ox;
        final int oz = g.oz;
        for (int i = 0; i < g.cls.length; i++) {
            switch (g.cls[i]) {
                case CLS_SEA -> g.seaCells++;
                case CLS_BEACH -> g.beachCells++;
                case CLS_HIGH -> g.highCells++;
                default -> g.unknownCells++;
            }
        }

        for (int di = 0; di < 4; di++) {
            final int dx = DIR_X[di];
            final int dz = DIR_Z[di];
            // The shore axis is whichever axis D is not on.
            final int ux = dx == 0 ? 1 : 0;
            final int uz = dx == 0 ? 0 : 1;
            for (int a = 0; a < size; a++) {
                int start = -1;
                for (int b = 0; b <= size; b++) {
                    boolean ok = false;
                    if (b < size) {
                        final int gx = ux == 1 ? b : a;
                        final int gz = uz == 1 ? b : a;
                        final int nx = gx + dx;
                        final int nz = gz + dz;
                        if (nx >= 0 && nx < size && nz >= 0 && nz < size)
                            ok = g.cls[gz * size + gx] == CLS_SEA
                                    && g.cls[nz * size + nx] != CLS_SEA;
                    }
                    if (ok) {
                        if (start < 0)
                            start = b;
                    } else if (start >= 0) {
                        final int gx0 = ux == 1 ? start : a;
                        final int gz0 = uz == 1 ? start : a;
                        addRun(g, ox + gx0, oz + gz0, ux, uz, dx, dz, b - start);
                        start = -1;
                    }
                }
            }
        }
    }

    /**
     * Offline test seam: the whole build, on a grid the caller has already classified,
     * with no {@link Level}. Runs the SAME {@link #collectRuns} and {@link #build} the
     * game runs - nothing here is a re-implementation - so whatever it draws is what the
     * game would draw for that terrain.
     */
    static void simulate(final Grid g, final float p, final Quads out) {
        collectRuns(g);
        build(g, p, null, out);
    }

    private static byte classify(final Level level, final int x, final int z,
                                 final int waterTop, final BlockPos.MutableBlockPos p) {
        // Cheapest question first: one fluid read at the water plane.
        p.set(x, waterTop, z);
        final FluidState fs = level.getFluidState(p);
        final boolean isSea = !fs.isEmpty() && fs.is(FluidTags.WATER);

        int ground = Integer.MIN_VALUE;
        for (int y = waterTop + WINDOW_HI; y >= waterTop + WINDOW_LO; y--) {
            p.set(x, y, z);
            final BlockState s = level.getBlockState(p);
            if (s.isAir())
                continue;
            final FluidState own = s.getFluidState();
            if (!own.isEmpty() && own.is(FluidTags.WATER))
                continue;
            ground = y;
            break;
        }

        if (ground == waterTop)
            return CLS_BEACH;
        if (ground > waterTop)
            return CLS_HIGH;
        return isSea ? CLS_SEA : CLS_UNKNOWN;
    }

    private static void addRun(final Grid g, final int wx0, final int wz0,
                               final int ux, final int uz, final int dx, final int dz,
                               final int len) {
        final short[] d = new short[len];
        final byte[] stopHigh = new byte[len];
        for (int i = 0; i < len; i++) {
            int x = wx0 + i * ux + dx;
            int z = wz0 + i * uz + dz;
            int dd = 0;
            while (g.inGrid(x, z) && g.cls[g.idx(x, z)] == CLS_BEACH) {
                dd++;
                x += dx;
                z += dz;
                if (dd >= D_SCAN_MAX)
                    break;
            }
            d[i] = (short) dd;
            // Out of window is NOT a wall: it only means we did not look.
            stopHigh[i] = (byte) (g.inGrid(x, z) && g.cls[g.idx(x, z)] == CLS_HIGH ? 1 : 0);
        }
        g.runs.add(new Run(wx0, wz0, ux, uz, dx, dz, len, d, stopHigh));
        g.runCells += len;
    }

