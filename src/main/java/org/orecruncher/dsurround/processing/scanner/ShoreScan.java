    /** A drawn quadrilateral: texture slot, height, packed light, four corners. */
    public static final class ShoreQuad {
        public int tex;
        public float y;
        public int light;
        /**
         * Vertex colour, 0xRRGGBB. Every emission site states its own -
         * {@link #FOAM_RGB} for the foam, the biome water colour for the film,
         * magenta for {@link #buildDebug} - so a recycled slot can never hand
         * one quad another's colour.
         */
        public int rgb = FOAM_RGB;
        /** Vertex alpha, 0..255: the window-edge fade, also stated per emitter. */
        public int alpha = 255;
        public final float[] wx = new float[4];
        public final float[] wz = new float[4];
        public final float[] u = new float[4];
        public final float[] v = new float[4];
    }

    /** A reusable quad buffer. Cleared and refilled every rebuild. */
    public static final class Quads {
        public ShoreQuad[] items = new ShoreQuad[256];
        public int count = 0;

        public void clear() {
            this.count = 0;
        }

        public ShoreQuad next() {
            if (this.count >= this.items.length)
                this.items = Arrays.copyOf(this.items, this.items.length * 2);
            ShoreQuad q = this.items[this.count];
            if (q == null) {
                q = new ShoreQuad();
                this.items[this.count] = q;
            }
            // No colour/alpha reset here on purpose. The pool is shared, so a
            // reset would silently become the foam's colour - and it is not the
            // foam's colour to state: every emitter sets both fields on the quad
            // it takes (foam FOAM_RGB, film the biome water colour, debug
            // magenta), which is the only way a slot can never recolour a quad.
            // Do not "restore" a white reset here: with 0xFFFFFF being the
            // identity the on-screen result is identical, so a reset buys
            // nothing and hides which emitter owns the colour.
            this.count++;
            return q;
        }
    }

    /**
     * Turns a frozen {@link Grid} plus a swell level {@code p} in 0..1 into
     * drawable quads. No block reads: everything here is arithmetic over the
     * snapshot, so it is cheap enough to run every tick.
     */
    public static void build(final Grid g, final float p, final Level level, final Quads out) {
        out.clear();
        Arrays.fill(g.filled, (byte) 0);
        Arrays.fill(g.cov, 0F);
        Arrays.fill(g.ftype, (byte) 0);
        Arrays.fill(g.fdir, (byte) 0);
        Arrays.fill(g.used, (byte) 0);
        g.foamCells = 0;
        g.filmQuads = 0;
        g.lineTexels = 0F;
        g.lineBlocks = 0F;
        g.filmTexels = 0F;
        g.filmBlocks = 0F;

        // ---- run-up, the three gates, and the wet sand they produce ----
        for (final Run r : g.runs) {
            for (int i = 0; i < r.len; i++) {
                final int d = r.d[i];
                final int cap = r.stopHigh[i] == 1 ? d : Math.max(0, d - KEEP_DRY_IF_NO_WALL);
                // B form, on purpose: clip the beach first, then scale. The A form
                // (scale, then clip) lets a wide beach be finished by p=0.46 while a
                // narrow one needs p=0.84, so one wave arrives at different times
                // along its own length.
                r.f[i] = Math.min(cap, p * Math.min(d, RUNUP_MAX));
            }
            // Symmetric clamp: two sweeps converge (it is a distance transform,
            // not an iterative relaxation). Runs on floats, so a neighbour offset
            // by 0.3 of a block stays offset by 0.3 - rounding here would undo
            // everything the fractional front buys.
            for (int i = 1; i < r.len; i++)
                r.f[i] = Math.min(r.f[i], r.f[i - 1] + MAX_STEP);
            for (int i = r.len - 2; i >= 0; i--)
                r.f[i] = Math.min(r.f[i], r.f[i + 1] + MAX_STEP);

            // Paint the water in two parts: every cell the front has passed is
            // fully wet, and the single cell it is crossing is wet in
            // proportion. That second part is the difference between a line that
            // creeps and a line that teleports one block every few ticks.
            for (int i = 0; i < r.len; i++) {
                final float f = r.f[i];
                final int whole = (int) f;              // floor, f >= 0 always
                final float frac = f - whole;
                final int x = r.startX + i * r.ux;
                final int z = r.startZ + i * r.uz;
                for (int k = 1; k <= whole; k++) {
                    final int fx = x + k * r.dx;
                    final int fz = z + k * r.dz;
                    if (g.inGrid(fx, fz)) {
                        final int gi = g.idx(fx, fz);
                        g.filled[gi] = 1;
                        if (g.cov[gi] < 1F)
                            g.cov[gi] = 1F;
                    }
                }
                if (frac > 0.02F) {
                    final int fx = x + (whole + 1) * r.dx;
                    final int fz = z + (whole + 1) * r.dz;
                    if (g.inGrid(fx, fz)) {
                        final int gi = g.idx(fx, fz);
                        g.filled[gi] = 1;
                        // Several runs can reach one cell at the front of a headland.
                        if (g.cov[gi] < frac)
                            g.cov[gi] = frac;
                    }
                }
            }
        }

        // ---- the foam line ----
        final int size = g.size;
        for (int gz = 0; gz < size; gz++) {
            for (int gx = 0; gx < size; gx++) {
                final int gi = gz * size + gx;
                if (!inUnion(g, gi))
                    continue;
                int mask = 0;
                int count = 0;
                for (int k = 0; k < 4; k++) {
                    final int nx = gx + DIR_X[k];
                    final int nz = gz + DIR_Z[k];
                    if (nx < 0 || nx >= size || nz < 0 || nz >= size)
                        continue;
                    if (!inUnion(g, nz * size + nx)) {
                        mask |= 1 << k;
                        count++;
                    }
                }
                if (count == 0)
                    continue;
                g.foamCells++;
                if (count == 1) {
                    g.ftype[gi] = F_STRAIGHT;
                    g.fdir[gi] = (byte) mask;
                } else {
                    final int[] pair = orthogonalPair(mask);
                    if (pair == null) {
                        // Two opposite dry neighbours: a one-cell channel. Both
                        // banks are drawn by their own runs; nothing to add.
                        continue;
                    }
                    g.fdir[gi] = (byte) cornerIndex((1 << pair[0]) | (1 << pair[1]));
                    // The diagonal decides convex from concave: dry diagonal is a
                    // headland the water wraps around, wet diagonal is a notch the
                    // water sits inside. Unit-checked against two hand-drawn
                    // answers in the twin; concave simply never showed up in the
                    // synthetic maps.
                    final int cx2 = gx + DIR_X[pair[0]] + DIR_X[pair[1]];
                    final int cz2 = gz + DIR_Z[pair[0]] + DIR_Z[pair[1]];
                    final boolean diagonalDry = !g.inGrid(cx2, cz2) || !inUnion(g, cz2 * size + cx2);
                    g.ftype[gi] = diagonalDry ? F_CONVEX : F_CONCAVE;
                }
            }
        }

        // ---- emit: the water film first (it lies under the foam) ----
        emitFilm(g, level, out);
        for (int gz = 0; gz < size; gz++) {
            for (int gx = 0; gx < size; gx++) {
                final int gi = gz * size + gx;
                final byte t = g.ftype[gi];
                if (t == F_NONE || !g.inRenderArea(g.ox + gx, g.oz + gz))
                    continue;
                if (t == F_STRAIGHT) {
                    final int li = dirIndex(g.fdir[gi]);
                    final int ux = -DIR_Z[li];
                    final int uz = DIR_X[li];
                    // Only the first cell of a run of straights draws the strip;
                    // the rest are swallowed by its length.
                    if (isDrawnStraight(g, gx - ux, gz - uz, li))
                        continue;
                    int len = 1;
                    while (isDrawnStraight(g, gx + len * ux, gz + len * uz, li))
                        len++;
                    emitStrip(g, level, gx, gz, li, ux, uz, len, out);
                } else {
                    emitCorner(g, level, gx, gz, t == F_CONVEX, g.fdir[gi], out);
                }
            }
        }

        tallyQuads(g, out);
    }

    /**
     * Per-type quad counts, for the diagnostics line and the log. They are read
     * off the quads actually produced, never recomputed from the grids - a
     * diagnostic that estimates is worse than one that is missing.
     */
    private static void tallyQuads(final Grid g, final Quads out) {
        g.stripQuads = 0;
        g.capQuads = 0;
        g.cornerQuads = 0;
        g.filmQuads = 0;
        g.filledCells = 0;
        for (int i = 0; i < out.count; i++) {
            final int tex = out.items[i].tex;
            if (tex == TEX_STRIP) g.stripQuads++;
            else if (tex == TEX_CAP) g.capQuads++;
            else if (tex == TEX_FILM) g.filmQuads++;
            else g.cornerQuads++;
        }
        for (int i = 0; i < g.filled.length; i++)
            if (g.filled[i] == 1) g.filledCells++;
    }

    private static boolean inUnion(final Grid g, final int gi) {
        return g.cls[gi] == CLS_SEA || g.filled[gi] == 1;
    }

    private static int dirIndex(final int mask) {
        for (int k = 0; k < 4; k++)
            if ((mask & (1 << k)) != 0)
                return k;
        return 0;
    }

    /** Two dry directions that are perpendicular, or null when they are opposite. */
    private static int[] orthogonalPair(final int mask) {
        for (int a = 0; a < 4; a++) {
            if ((mask & (1 << a)) == 0)
                continue;
            for (int b = a + 1; b < 4; b++) {
                if ((mask & (1 << b)) == 0)
                    continue;
                // 0/1 are N/S and 2/3 are W/E - the two opposite pairs.
                if (a == 0 && b == 1)
                    continue;
                if (a == 2 && b == 3)
                    continue;
                return new int[]{a, b};
            }
        }
        return null;
    }

    /** Which corner of the cell the land sits in: 0 NW, 1 NE, 2 SE, 3 SW. */
    private static int cornerIndex(final int mask) {
        final boolean south = (mask & 0b0010) != 0;
        final boolean east = (mask & 0b1000) != 0;
        return south ? (east ? 2 : 3) : (east ? 1 : 0);
    }

    private static boolean isDrawnStraight(final Grid g, final int gx, final int gz, final int li) {
        if (gx < 0 || gx >= g.size || gz < 0 || gz >= g.size)
            return false;
        if (!g.inRenderArea(g.ox + gx, g.oz + gz))
            return false;
        final int gi = gz * g.size + gx;
        return g.ftype[gi] == F_STRAIGHT && g.fdir[gi] == (byte) (1 << li);
    }

    // ---- emission --------------------------------------------------------

    private static void emitStrip(final Grid g, final Level level, final int gx, final int gz,
                                  final int li, final int ux, final int uz, final int len,
                                  final Quads out) {
        final int x = g.ox + gx;
        final int z = g.oz + gz;
        final int lx = DIR_X[li];
        final int lz = DIR_Z[li];
        final float ax = x + 0.5F;
        final float az = z + 0.5F;
        final int light = lightAt(level, g, x, z);

        // The tile is 64 units wide = 4 blocks, so 16 units per block. Anchoring
        // u on the world column keeps the wave continuous across cell seams and
        // across rebuilds.
        final float sStart = (ax * ux + az * uz) - 0.5F;
        final int startUnits = Math.floorMod(Math.round(sStart * 16F), 64);

        // A run crosses two kinds of cells: open water (band at the water plane)
        // and wet sand it has flooded (band one block up). A single quad is flat,
        // so it is cut wherever the surface height or the window-edge fade steps -
        // without the height cut the wet-sand half of the run is drawn at the
        // water plane and buried inside the beach, which reads as a broken line.
        int offset = 0;
        while (offset < len) {
            final float y = surfaceBase(g, gx + offset * ux, gz + offset * uz) + FOAM_LIFT;
            final int alpha = frontAlpha(g, gx + offset * ux, gz + offset * uz);
            int run = 1;
            while (offset + run < len
                    && surfaceBase(g, gx + (offset + run) * ux, gz + (offset + run) * uz) + FOAM_LIFT == y
                    && frontAlpha(g, gx + (offset + run) * ux, gz + (offset + run) * uz) == alpha)
                run++;
            if (alpha == 0) {
                offset += run;
                continue;
            }
            while (run > 0) {
                // The body is also cut at 4-block tile boundaries rather than
                // letting u run past 1: a texture sampled with CLAMP would smear
                // the last cell of a long straight into a streak, and which wrap
                // mode the manager gives a plain (non-atlas) texture is not
                // something this class can see. Cutting costs a quad every four
                // blocks and keeps every u inside 0..1.
                final int units = Math.floorMod(startUnits + offset * 16, 64);
                final int chunk = Math.min(run, 4 - (units >> 4));
                final float u0 = units / 64F;
                final float u1 = u0 + chunk * 0.25F;
                final float a0 = offset - 0.5F;
                final float a1 = offset + chunk - 0.5F;
                g.lineTexels += (u1 - u0) * STRIP_TEX_WIDTH;
                g.lineBlocks += chunk;
                final ShoreQuad body = out.next();
                body.tex = TEX_STRIP;
                body.y = y;
                body.light = light;
                body.rgb = FOAM_RGB;
                body.alpha = alpha;
                put(body, 0, ax, az, ux, uz, lx, lz, a0, 0F, u0);
                put(body, 1, ax, az, ux, uz, lx, lz, a1, 0F, u1);
                put(body, 2, ax, az, ux, uz, lx, lz, a1, 1F, u1);
                put(body, 3, ax, az, ux, uz, lx, lz, a0, 1F, u0);
                offset += chunk;
                run -= chunk;
            }
        }

        // Caps, but only where the line really ends: a strip that runs into a
        // corner tile is continued by that tile, and capping it would stack two
        // layers of foam on one cell.
        if (!isDrawnStraight(g, gx - ux, gz - uz, li)) {
            final int alpha = frontAlpha(g, gx, gz);
            if (alpha > 0) {
                emitCap(ax, az, ux, uz, lx, lz, -0.75F, -0.5F, 0F, 1F, y(g, gx, gz), light, alpha, out);
                // A cap lays the whole 4-texel tile across a quarter block, which
                // is the same 16 texels per block the body uses.
                g.lineTexels += CAP_TEX_WIDTH;
                g.lineBlocks += 0.25F;
            }
        }
        if (!isDrawnStraight(g, gx + len * ux, gz + len * uz, li)) {
            final int alpha = frontAlpha(g, gx + (len - 1) * ux, gz + (len - 1) * uz);
            if (alpha > 0) {
                emitCap(ax, az, ux, uz, lx, lz, len - 0.5F, len - 0.25F, 1F, 0F, y(g, gx, gz), light, alpha, out);
                g.lineTexels += CAP_TEX_WIDTH;
                g.lineBlocks += 0.25F;
            }
        }
    }

    /**
     * The film: a thin sheet of water over the sand the wave has flooded, one
     * quad per greedy rectangle. Only {@code filled} cells are covered - the
     * sea itself is vanilla's water. The colour is the local biome water
     * colour, so a swamp shore films brown and a frozen one pale without any
     * per-biome table here.
     */
    private static void emitFilm(final Grid g, final Level level, final Quads out) {
        final int size = g.size;
        // Cells the front is still crossing: they belong to no rectangle (a
        // greedy merge would lose their fraction, and with it the fade), so they
        // are claimed here and drawn one by one. This is the film's advance -
        // the rest of the sheet is already fully wet and merges as before.
        for (int gz = 0; gz < size; gz++) {
            for (int gx = 0; gx < size; gx++) {
                final int gi = gz * size + gx;
                if (g.filled[gi] != 1 || g.cov[gi] >= 1F || g.cov[gi] <= 0F)
                    continue;
                g.used[gi] = 1;
                if (g.inRenderArea(g.ox + gx, g.oz + gz))
                    emitFilmRect(g, level, gx, gz, 1, 1, out);
            }
        }

        for (int gz = 0; gz < size; gz++) {
            for (int gx = 0; gx < size; gx++) {
                final int gi = gz * size + gx;
                if (g.filled[gi] != 1 || g.used[gi] == 1 || !g.inRenderArea(g.ox + gx, g.oz + gz))
                    continue;
                int w = 1;
                while (gx + w < size && g.filled[gi + w] == 1 && g.used[gi + w] == 0
                        && g.inRenderArea(g.ox + gx + w, g.oz + gz))
                    w++;
                int h = 1;
                grow:
                while (gz + h < size) {
                    for (int k = 0; k < w; k++) {
                        final int gj = (gz + h) * size + gx + k;
                        if (g.filled[gj] != 1 || g.used[gj] == 1
                                || !g.inRenderArea(g.ox + gx + k, g.oz + gz + h))
                            break grow;
                    }
                    h++;
                }
                for (int dz = 0; dz < h; dz++)
                    for (int dx = 0; dx < w; dx++)
                        g.used[(gz + dz) * size + gx + dx] = 1;
                emitFilmRect(g, level, gx, gz, w, h, out);
            }
        }
    }

    private static void emitFilmRect(final Grid g, final Level level,
                                     final int gx, final int gz, final int w, final int h,
                                     final Quads out) {
        int alpha = 255;
        for (int dz = 0; dz < h; dz++)
            for (int dx = 0; dx < w; dx++)
                alpha = Math.min(alpha, frontAlpha(g, gx + dx, gz + dz));
        if (alpha == 0)
            return;
        final int x = g.ox + gx;
        final int z = g.oz + gz;
        final int cx = x + w / 2;
        final int cz = z + h / 2;
        final ShoreQuad q = out.next();
        q.tex = TEX_FILM;
        // Every filled cell is beach, so one height covers the rect.
        q.y = surfaceBase(g, gx, gz) + FILM_LIFT;
        q.light = lightAt(level, g, cx, cz);
        // The film is the mirror of the foam: its 16x16 texture is pure white, so
        // the colour has to come from here - the local biome water colour
        // (ocean / deep_ocean / beach / stony_shore are all #3F76E4).
        // The biome water colour scaled exactly as vanilla's water texture scales
        // it, so the film and the sea are the same paint at the same alpha.
        q.rgb = scaleRgb(BiomeColors.getAverageWaterColor(level, CURSOR.set(cx, g.waterTop + 1, cz)) & 0xFFFFFF,
                WATER_TINT_SCALE);
        q.alpha = (int) (alpha * FILM_ALPHA);
        // UV density, design gauge: 16x16 sheet, one texel = 1/16 block, so a
        // rect of w blocks spans w in u. The sheet is a single colour today, so
        // this cannot change a pixel - it is here so the density is right by
        // construction if the film ever gains grain, instead of silently
        // collapsing to 16/w texels per block on the large merged rectangles.
        g.filmTexels += (float) (w + h) * FILM_TEX_WIDTH * 0.5F;
        g.filmBlocks += w + h;
        g.filmQuads++;        q.wx[0] = x;         q.wz[0] = z;         q.u[0] = 0F;    q.v[0] = 0F;
        q.wx[1] = x + w;     q.wz[1] = z;         q.u[1] = w;     q.v[1] = 0F;
        q.wx[2] = x + w;     q.wz[2] = z + h;     q.u[2] = w;     q.v[2] = h;
        q.wx[3] = x;         q.wz[3] = z + h;     q.u[3] = 0F;    q.v[3] = h;
    }

    /**
     * Opacity of the flood film, 0..1.
     *
     * <p><b>180/255 is not a taste knob either.</b> It is the alpha vanilla's
     * water texture carries, so a film drawn at this alpha over a background is
     * <em>bit-identical</em> to the water surface drawn over the same
     * background: same paint ({@link #WATER_TINT_SCALE}), same alpha. Raise it
     * and the wet sand the film is supposed to be lying on stops showing
     * through; lower it and the film stops matching the sea it runs into.
     * The 0.70 this replaced happened to sit within 0.6% of the right number -
     * the colour was the whole defect.</p>
     */
    private static final float FILM_ALPHA = 180F / 255F;

    /**
     * Alpha for a cell: 0 in the unstable margin ring, fading in over
     * {@link #FADE_BLOCKS} blocks so the scan window's edge reads as distance,
     * not as a guillotine.
     */
    private static int edgeAlpha(final Grid g, final int gx, final int gz) {
        final int d = Math.min(Math.min(gx, gz), Math.min(g.size - 1 - gx, g.size - 1 - gz));
        final int t = d - RENDER_MARGIN;
        if (t >= FADE_BLOCKS)
            return 255;
        if (t <= 0)
            return EDGE_FLOOR_ALPHA;
        return EDGE_FLOOR_ALPHA + t * (255 - EDGE_FLOOR_ALPHA) / FADE_BLOCKS;
    }

    /**
     * {@link #edgeAlpha} scaled by how far the front has crossed this cell.
     * Cells the sea already owns get the full value - only land the wave is
     * currently crossing is partial. This is what turns the steppy advance into
     * a fade: a cell the front has half crossed draws at half opacity, so the
     * line never has to decide which side of a block boundary it is on.
     */
    private static int frontAlpha(final Grid g, final int gx, final int gz) {
        final int a = edgeAlpha(g, gx, gz);
        if (a <= 0)
            return 0;
        final int gi = gz * g.size + gx;
        if (g.filled[gi] != 1)
            return a;
        final float c = g.cov[gi];
        return c >= 1F ? a : Math.max(1, (int) (a * c));
    }

    /**
     * A cap is a quarter-block sliver of band that fades out along the shore, so
     * a line that stops - at a corner of the window, or at the end of a spit -
     * tapers instead of ending in a wall. The tile's opaque column is at
     * {@code u = 1}, so {@code uAtA0/uAtA1} put that column on whichever end
     * touches the body; the far cap passes them swapped, which mirrors the tile.
     */
    private static void emitCap(final float ax, final float az,
                                final int ux, final int uz, final int lx, final int lz,
                                final float a0, final float a1,
                                final float uAtA0, final float uAtA1,
                                final float y, final int light, final int alpha, final Quads out) {
        final ShoreQuad q = out.next();
        q.tex = TEX_CAP;
        q.y = y;
        q.light = light;
        q.rgb = FOAM_RGB;
        q.alpha = alpha;
        put(q, 0, ax, az, ux, uz, lx, lz, a0, 0F, uAtA0);
        put(q, 1, ax, az, ux, uz, lx, lz, a1, 0F, uAtA1);
        put(q, 2, ax, az, ux, uz, lx, lz, a1, 1F, uAtA1);
        put(q, 3, ax, az, ux, uz, lx, lz, a0, 1F, uAtA0);
    }

    private static void emitCorner(final Grid g, final Level level, final int gx, final int gz,
                                   final boolean convex, final int landCorner, final Quads out) {
        final int x = g.ox + gx;
        final int z = g.oz + gz;
        // Both arms of the corner have their own phase; average them rather than
        // picking one, so neither arm jumps at the joint.
        final int w = (WAVE[Math.floorMod(x, 64)] + WAVE[Math.floorMod(z, 64)] + 1) >> 1;
        final int slot = (convex ? TEX_CONVEX : TEX_CONCAVE) + (w < 0 ? 0 : w > 3 ? 3 : w);

        // One 16x16 tile across one cell: the same 16 texels per block again,
        // which is why the corner tiles read at the same grain as the strip.
        g.lineTexels += CORNER_TEX_WIDTH;
        g.lineBlocks += 1F;

        final ShoreQuad q = out.next();
        q.tex = slot;
        q.y = surfaceBase(g, gx, gz) + FOAM_LIFT;
        q.light = lightAt(level, g, x, z);
        q.rgb = FOAM_RGB;
        q.alpha = frontAlpha(g, gx, gz);

        // Cell corners: 0 NW, 1 NE, 2 SE, 3 SW. The tile's land sits at its own
        // UV origin, so rotating means handing corner i the UV of corner i - j.
        putCorner(q, 0, x, z, landCorner);
        putCorner(q, 1, x, z, landCorner);
        putCorner(q, 2, x, z, landCorner);
        putCorner(q, 3, x, z, landCorner);
    }

    private static void putCorner(final ShoreQuad q, final int i, final int x, final int z, final int landCorner) {
        // World position of cell corner i.
        final float wx = x + ((i == 1 || i == 2) ? 1F : 0F);
        final float wz = z + (i >= 2 ? 1F : 0F);
        final int uvIdx = Math.floorMod(i - landCorner, 4);
        q.wx[i] = wx;
        q.wz[i] = wz;
        q.u[i] = CORNER_UV[uvIdx][0];
        q.v[i] = CORNER_UV[uvIdx][1];
    }

    /**
     * Places one corner. {@code along} is the offset from the cell centre along
     * the shore axis, {@code v} 0 at the land edge and 1 at the water edge, so
     * the band always grows away from the beach.
     */
    private static void put(final ShoreQuad q, final int i, final float ax, final float az,
                            final int ux, final int uz, final int lx, final int lz,
                            final float along, final float v, final float u) {
        final float off = 0.5F - v;
        q.wx[i] = ax + along * ux + off * lx;
        q.wz[i] = az + along * uz + off * lz;
        q.u[i] = u;
        q.v[i] = v;
    }

    /**
     * Surface height without any lift: open water at {@code waterTop + 8/9},
     * anything the wave has flooded (wet sand) one block higher. Wet and dry
     * cells along one strip differ by exactly this step, which is why strips
     * are cut where it changes.
     */
    private static float surfaceBase(final Grid g, final int gx, final int gz) {
        final byte c = g.cls[gz * g.size + gx];
        return c == CLS_SEA ? g.waterTop + 8F / 9F : g.waterTop + 1F;
    }

    /** Foam height: the cell's own surface plus the foam lift. */
    private static float y(final Grid g, final int gx, final int gz) {
        return surfaceBase(g, gx, gz) + FOAM_LIFT;
    }

    private static int lightAt(final Level level, final Grid g, final int x, final int z) {
        return LevelRenderer.getLightColor(level, CURSOR.set(x, g.waterTop + 1, z));
    }

    /**
     * Java's {@code Math.round} is {@code floor(x + 0.5)}; Python's {@code round}
     * is banker's rounding. The twin has to use the same one or a smooth front
     * measures as sawtooth.
     *
     * <p>Kept although the front no longer rounds: the offline twin still needs
     * it to reproduce the old integer behaviour when comparing, and it is the
     * reason that change was measured rather than guessed.</p>
     */
    @SuppressWarnings("unused")
    private static int jround(final float x) {
        return (int) Math.floor(x + 0.5);
    }

