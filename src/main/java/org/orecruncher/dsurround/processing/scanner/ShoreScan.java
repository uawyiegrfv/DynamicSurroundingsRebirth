    /** A drawn quadrilateral: texture slot, height, packed light, four corners. */
    public static final class ShoreQuad {
        public int tex;
        public float y;
        public int light;
        /**
         * Vertex colour, 0xRRGGBB. Every emission site states its own -
         * {@link #FOAM_RGB} for the foam, the biome water colour for the film,
         * magenta for {@link #buildDebug} - so a recycled slot can never hand
         * one quad another's colour.
         */
        public int rgb = FOAM_RGB;
        /** Vertex alpha, 0..255: the window-edge fade, also stated per emitter. */
        public int alpha = 255;
        public final float[] wx = new float[4];
        public final float[] wz = new float[4];
        public final float[] u = new float[4];
        public final float[] v = new float[4];
    }

    /** A reusable quad buffer. Cleared and refilled every rebuild. */
    public static final class Quads {
        public ShoreQuad[] items = new ShoreQuad[256];
        public int count = 0;

        public void clear() {
            this.count = 0;
        }

        public ShoreQuad next() {
            if (this.count >= this.items.length)
                this.items = Arrays.copyOf(this.items, this.items.length * 2);
            ShoreQuad q = this.items[this.count];
            if (q == null) {
                q = new ShoreQuad();
                this.items[this.count] = q;
            }
            // No colour/alpha reset here on purpose. The pool is shared, so a
            // reset would silently become the foam's colour - and it is not the
            // foam's colour to state: every emitter sets both fields on the quad
            // it takes (foam FOAM_RGB, film the biome water colour, debug
            // magenta), which is the only way a slot can never recolour a quad.
            // Do not "restore" a white reset here: with 0xFFFFFF being the
            // identity the on-screen result is identical, so a reset buys
            // nothing and hides which emitter owns the colour.
            this.count++;
            return q;
        }
    }

    /**
     * Turns a frozen {@link Grid} plus a swell level {@code p} in 0..1 into
     * drawable quads. No block reads: everything here is arithmetic over the
     * snapshot, so it is cheap enough to run every tick.
     */
    public static void build(final Grid g, final float p, final Level level, final Quads out) {
        build(g, p, level, out, false);
    }

    /**
     * As {@link #build(Grid, float, Level, Quads)}, with the film's vertex colour
     * optionally forced to {@link #FILM_DEBUG_RGB}.
     *
     * <p>The flag reaches only {@link #emitFilmRect}: the geometry, the height and
     * the alpha of every quad are untouched, so the debug picture still shows the
     * film's real shape and its real fade. That is deliberate - a switch that
     * changed the geometry too could not answer which of the two was wrong.</p>
     */
    public static void build(final Grid g, final float p, final Level level, final Quads out,
                             final boolean filmDebugColor) {
        build(g, p, level, out, filmDebugColor, true, true);
    }

    public static void build(final Grid g, final float p, final Level level, final Quads out,
                             final boolean filmDebugColor, final boolean filmEnabled,
                             final boolean foldLine) {
        out.clear();
        Arrays.fill(g.filled, (byte) 0);
        Arrays.fill(g.cov, 0F);
        Arrays.fill(g.ftype, (byte) 0);
        Arrays.fill(g.fdir, (byte) 0);
        Arrays.fill(g.used, (byte) 0);
        g.foamCells = 0;
        g.filmQuads = 0;
        g.lineTexels = 0F;
        g.lineBlocks = 0F;
        g.filmTexels = 0F;
        g.filmBlocks = 0F;

        // ---- run-up, the three gates, and the wet sand they produce ----
        for (final Run r : g.runs) {
            for (int i = 0; i < r.len; i++) {
                final int d = r.d[i];
                final int cap = r.stopHigh[i] == 1 ? d : Math.max(0, d - KEEP_DRY_IF_NO_WALL);
                // B form, on purpose: clip the beach first, then scale. The A form
                // (scale, then clip) lets a wide beach be finished by p=0.46 while a
                // narrow one needs p=0.84, so one wave arrives at different times
                // along its own length.
                r.f[i] = Math.min(cap, p * Math.min(d, RUNUP_MAX));
            }
            // Symmetric clamp: two sweeps converge (it is a distance transform,
            // not an iterative relaxation). Runs on floats, so a neighbour offset
            // by 0.3 of a block stays offset by 0.3 - rounding here would undo
            // everything the fractional front buys.
            for (int i = 1; i < r.len; i++)
                r.f[i] = Math.min(r.f[i], r.f[i - 1] + MAX_STEP);
            for (int i = r.len - 2; i >= 0; i--)
                r.f[i] = Math.min(r.f[i], r.f[i + 1] + MAX_STEP);

            // Paint the water in two parts: every cell the front has passed is
            // fully wet, and the single cell it is crossing is wet in
            // proportion. That second part is the difference between a line that
            // creeps and a line that teleports one block every few ticks.
            for (int i = 0; i < r.len; i++) {
                final float f = r.f[i];
                final int whole = (int) f;              // floor, f >= 0 always
                final float frac = f - whole;
                final int x = r.startX + i * r.ux;
                final int z = r.startZ + i * r.uz;
                for (int k = 1; k <= whole; k++) {
                    final int fx = x + k * r.dx;
                    final int fz = z + k * r.dz;
                    if (g.inGrid(fx, fz)) {
                        final int gi = g.idx(fx, fz);
                        g.filled[gi] = 1;
                        if (g.cov[gi] < 1F)
                            g.cov[gi] = 1F;
                    }
                }
                if (frac > 0.02F) {
                    final int fx = x + (whole + 1) * r.dx;
                    final int fz = z + (whole + 1) * r.dz;
                    if (g.inGrid(fx, fz)) {
                        final int gi = g.idx(fx, fz);
                        g.filled[gi] = 1;
                        // Several runs can reach one cell at the front of a headland.
                        if (g.cov[gi] < frac)
                            g.cov[gi] = frac;
                    }
                }
            }
        }

        // ---- the foam line ----
        if (foldLine) {
            collectShoreEdges(g);
            emitShoreLine(g, level, p, out);
            tallyQuads(g, out);
            return;
        }
        final int size = g.size;
        for (int gz = 0; gz < size; gz++) {
            for (int gx = 0; gx < size; gx++) {
                final int gi = gz * size + gx;
                if (!inUnion(g, gi))
                    continue;
                int mask = 0;
                int count = 0;
                for (int k = 0; k < 4; k++) {
                    final int nx = gx + DIR_X[k];
                    final int nz = gz + DIR_Z[k];
                    if (nx < 0 || nx >= size || nz < 0 || nz >= size)
                        continue;
                    if (!inUnion(g, nz * size + nx)) {
                        mask |= 1 << k;
                        count++;
                    }
                }
                if (count == 0)
                    continue;
                g.foamCells++;
                if (count == 1) {
                    g.ftype[gi] = F_STRAIGHT;
                    g.fdir[gi] = (byte) mask;
                } else {
                    final int[] pair = orthogonalPair(mask);
                    if (pair == null) {
                        // Two opposite dry neighbours: a one-cell channel. Both
                        // banks are drawn by their own runs; nothing to add.
                        continue;
                    }
                    g.fdir[gi] = (byte) cornerIndex((1 << pair[0]) | (1 << pair[1]));
                    // The diagonal decides convex from concave: dry diagonal is a
                    // headland the water wraps around, wet diagonal is a notch the
                    // water sits inside. Unit-checked against two hand-drawn
                    // answers in the twin; concave simply never showed up in the
                    // synthetic maps.
                    final int cx2 = gx + DIR_X[pair[0]] + DIR_X[pair[1]];
                    final int cz2 = gz + DIR_Z[pair[0]] + DIR_Z[pair[1]];
                    final boolean diagonalDry = !g.inGrid(cx2, cz2) || !inUnion(g, cz2 * size + cx2);
                    g.ftype[gi] = diagonalDry ? F_CONVEX : F_CONCAVE;
                }
            }
        }

        // ---- emit: the water film first (it lies under the foam) ----
        emitFilm(g, level, out, filmDebugColor);
        for (int gz = 0; gz < size; gz++) {
            for (int gx = 0; gx < size; gx++) {
                final int gi = gz * size + gx;
                final byte t = g.ftype[gi];
                if (t == F_NONE || !g.inRenderArea(g.ox + gx, g.oz + gz))
                    continue;
                if (t == F_STRAIGHT) {
                    final int li = dirIndex(g.fdir[gi]);
                    final int ux = -DIR_Z[li];
                    final int uz = DIR_X[li];
                    // Only the first cell of a run of straights draws the strip;
                    // the rest are swallowed by its length.
                    if (isDrawnStraight(g, gx - ux, gz - uz, li))
                        continue;
                    int len = 1;
                    while (isDrawnStraight(g, gx + len * ux, gz + len * uz, li))
                        len++;
                    emitStrip(g, level, gx, gz, li, ux, uz, len, out);
                } else {
                    emitCorner(g, level, gx, gz, t == F_CONVEX, g.fdir[gi], out);
                }
            }
        }

        tallyQuads(g, out);
    }

    /**
     * Per-type quad counts, for the diagnostics line and the log. They are read
     * off the quads actually produced, never recomputed from the grids - a
     * diagnostic that estimates is worse than one that is missing.
     */
    private static void tallyQuads(final Grid g, final Quads out) {
        g.stripQuads = 0;

        g.capQuads = 0;
        g.cornerQuads = 0;
        g.filmQuads = 0;
        g.filledCells = 0;
        for (int i = 0; i < out.count; i++) {
            final int tex = out.items[i].tex;
            if (tex == TEX_STRIP) g.stripQuads++;
            else if (tex == TEX_CAP) g.capQuads++;
            else if (tex == TEX_FILM) g.filmQuads++;
            else g.cornerQuads++;
        }
        for (int i = 0; i < g.filled.length; i++)
            if (g.filled[i] == 1) g.filledCells++;
    }

    /**
     * What the geometric self-check saw, and what it refused to draw.
     *
     * <p>Read off the quads that are about to be handed to the buffer, so the
     * numbers cannot disagree with the picture - see {@link #auditQuads}.</p>
     */
    public static final class Audit {
        /** Quads that survived. */
        public int quads;
        /** Quads dropped for spanning more than {@link #MAX_QUAD_SPAN} blocks. */
        public int droppedSpan;
        /** Quads dropped for sitting further than {@link #MAX_QUAD_DISTANCE} from the player. */
        public int droppedDistance;
        /** The widest x/z span actually seen, in blocks. */
        public float maxSpan;
        /** AABB of everything kept - the answer to "is it even in the window". */
        public int minX = Integer.MAX_VALUE;
        public int maxX = Integer.MIN_VALUE;
        public int minZ = Integer.MAX_VALUE;
        public int maxZ = Integer.MIN_VALUE;
        /** Nearest and furthest quad AABB corner, in blocks, from the player. */
        public float nearest = Float.MAX_VALUE;
        public float furthest;
        /** Per-type quad counts, so a dropped type is visible as a zero. */
        public final int[] perTex = new int[TEX_COUNT];

        public boolean droppedAnything() {
            return this.droppedSpan > 0 || this.droppedDistance > 0;
        }
    }

    /**
     * The geometric self-check: every quad about to be drawn is measured, and one
     * that is too wide or too far away is <b>dropped</b> rather than drawn.
     *
     * <p>This is the guard for the failure that produced the "one big plate"
     * report: a quad can be geometrically consistent with every rule in this
     * class and still be catastrophic on screen if a span is wrong by an order of
     * magnitude, and no amount of reading the rules back will catch it - the
     * numbers in the log will look fine. Measuring the quads that were actually
     * emitted is the only check that cannot drift from the rules.</p>
     *
     * <p>{@link #MAX_QUAD_SPAN} is the design's own largest unit (a 4-block strip
     * chunk, or a film tile cut to the same size), and {@link #MAX_QUAD_DISTANCE}
     * is {@code RANGE + 3}, one block more than a maximally stale window can
     * reach. Both are therefore unreachable by correct geometry: a drop means
     * something upstream broke, which is why the caller logs it loudly when
     * {@code debugLogging} is on.</p>
     */
    public static Audit auditQuads(final Grid g, final Quads out, final int px, final int pz) {
        final Audit audit = new Audit();
        int keep = 0;
        for (int i = 0; i < out.count; i++) {
            final ShoreQuad q = out.items[i];
            float minX = q.wx[0], maxX = q.wx[0], minZ = q.wz[0], maxZ = q.wz[0];
            for (int k = 1; k < 4; k++) {
                minX = Math.min(minX, q.wx[k]);
                maxX = Math.max(maxX, q.wx[k]);
                minZ = Math.min(minZ, q.wz[k]);
                maxZ = Math.max(maxZ, q.wz[k]);
            }
            final float span = Math.max(maxX - minX, maxZ - minZ);
            // Distance from the player to the quad's own box, so a long strip
            // lying across the view is judged by its nearest end, not its far one.
            final float dx = Math.max(0F, Math.max(minX - px, px - maxX));
            final float dz = Math.max(0F, Math.max(minZ - pz, pz - maxZ));
            final float distance = (float) Math.sqrt(dx * dx + dz * dz);

            if (span > MAX_QUAD_SPAN + 0.001F) {
                audit.droppedSpan++;
                continue;
            }
            if (distance > MAX_QUAD_DISTANCE) {
                audit.droppedDistance++;
                continue;
            }

            out.items[keep++] = q;
            audit.perTex[q.tex]++;
            audit.maxSpan = Math.max(audit.maxSpan, span);
            audit.nearest = Math.min(audit.nearest, distance);
            audit.furthest = Math.max(audit.furthest, distance);
            audit.minX = Math.min(audit.minX, (int) Math.floor(minX));
            audit.maxX = Math.max(audit.maxX, (int) Math.ceil(maxX));
            audit.minZ = Math.min(audit.minZ, (int) Math.floor(minZ));
            audit.maxZ = Math.max(audit.maxZ, (int) Math.ceil(maxZ));
        }
        out.count = keep;
        audit.quads = keep;
        if (keep == 0) {
            audit.nearest = 0F;
            audit.minX = audit.maxX = audit.minZ = audit.maxZ = 0;
        }
        return audit;
    }

    private static boolean inUnion(final Grid g, final int gi) {
        return g.cls[gi] == CLS_SEA || g.filled[gi] == 1;
    }

    private static int dirIndex(final int mask) {
        for (int k = 0; k < 4; k++)
            if ((mask & (1 << k)) != 0)
                return k;
        return 0;
    }

    /** Two dry directions that are perpendicular, or null when they are opposite. */
    private static int[] orthogonalPair(final int mask) {
        for (int a = 0; a < 4; a++) {
            if ((mask & (1 << a)) == 0)
                continue;
            for (int b = a + 1; b < 4; b++) {
                if ((mask & (1 << b)) == 0)
                    continue;
                // 0/1 are N/S and 2/3 are W/E - the two opposite pairs.
                if (a == 0 && b == 1)
                    continue;
                if (a == 2 && b == 3)
                    continue;
                return new int[]{a, b};
            }
        }
        return null;
    }

    /** Which corner of the cell the land sits in: 0 NW, 1 NE, 2 SE, 3 SW. */
    private static int cornerIndex(final int mask) {
        final boolean south = (mask & 0b0010) != 0;
        final boolean east = (mask & 0b1000) != 0;
        return south ? (east ? 2 : 3) : (east ? 1 : 0);
    }

    private static boolean isDrawnStraight(final Grid g, final int gx, final int gz, final int li) {
        if (gx < 0 || gx >= g.size || gz < 0 || gz >= g.size)
            return false;
        if (!g.inRenderArea(g.ox + gx, g.oz + gz))
            return false;
        final int gi = gz * g.size + gx;
        return g.ftype[gi] == F_STRAIGHT && g.fdir[gi] == (byte) (1 << li);
    }

    // ---- emission --------------------------------------------------------

    private static void emitStrip(final Grid g, final Level level, final int gx, final int gz,
                                  final int li, final int ux, final int uz, final int len,
                                  final Quads out) {
        final int x = g.ox + gx;
        final int z = g.oz + gz;
        final int lx = DIR_X[li];
        final int lz = DIR_Z[li];
        final float ax = x + 0.5F;
        final float az = z + 0.5F;
        final int light = lightAt(level, g, x, z);

        // The tile is 64 units wide = 4 blocks, so 16 units per block. Anchoring
        // u on the world column keeps the wave continuous across cell seams and
        // across rebuilds.
        final float sStart = (ax * ux + az * uz) - 0.5F;
        final int startUnits = Math.floorMod(Math.round(sStart * 16F), 64);

        // A run crosses two kinds of cells: open water (band at the water plane)
        // and wet sand it has flooded (band one block up). A single quad is flat,
        // so it is cut wherever the surface height or the window-edge fade steps -
        // without the height cut the wet-sand half of the run is drawn at the
        // water plane and buried inside the beach, which reads as a broken line.
        int offset = 0;
        while (offset < len) {
            final float y = surfaceBase(g, gx + offset * ux, gz + offset * uz) + FOAM_LIFT;
            final int alpha = frontAlpha(g, gx + offset * ux, gz + offset * uz);
            int run = 1;
            while (offset + run < len
                    && surfaceBase(g, gx + (offset + run) * ux, gz + (offset + run) * uz) + FOAM_LIFT == y
                    && frontAlpha(g, gx + (offset + run) * ux, gz + (offset + run) * uz) == alpha)
                run++;
            if (alpha == 0) {
                offset += run;
                continue;
            }
            while (run > 0) {
                // The body is also cut at 4-block tile boundaries rather than
                // letting u run past 1: a texture sampled with CLAMP would smear
                // the last cell of a long straight into a streak, and which wrap
                // mode the manager gives a plain (non-atlas) texture is not
                // something this class can see. Cutting costs a quad every four
                // blocks and keeps every u inside 0..1.
                final int units = Math.floorMod(startUnits + offset * 16, 64);
                final int chunk = Math.min(run, 4 - (units >> 4));
                final float u0 = units / 64F;
                final float u1 = u0 + chunk * 0.25F;
                final float a0 = offset - 0.5F;
                final float a1 = offset + chunk - 0.5F;
                g.lineTexels += (u1 - u0) * STRIP_TEX_WIDTH;
                g.lineBlocks += chunk;
                final ShoreQuad body = out.next();
                body.tex = TEX_STRIP;
                body.y = y;
                body.light = light;
                body.rgb = FOAM_RGB;
                body.alpha = alpha;
                put(body, 0, ax, az, ux, uz, lx, lz, a0, 0F, u0);
                put(body, 1, ax, az, ux, uz, lx, lz, a1, 0F, u1);
                put(body, 2, ax, az, ux, uz, lx, lz, a1, 1F, u1);
                put(body, 3, ax, az, ux, uz, lx, lz, a0, 1F, u0);
                offset += chunk;
                run -= chunk;
            }
        }

        // Caps, but only where the line really ends: a strip that runs into a
        // corner tile is continued by that tile, and capping it would stack two
        // layers of foam on one cell.
        if (!isDrawnStraight(g, gx - ux, gz - uz, li)) {
            final int alpha = frontAlpha(g, gx, gz);
            if (alpha > 0) {
                emitCap(ax, az, ux, uz, lx, lz, -0.75F, -0.5F, 0F, 1F, y(g, gx, gz), light, alpha, out);
                // A cap lays the whole 4-texel tile across a quarter block, which
                // is the same 16 texels per block the body uses.
                g.lineTexels += CAP_TEX_WIDTH;
                g.lineBlocks += 0.25F;
            }
        }
        if (!isDrawnStraight(g, gx + len * ux, gz + len * uz, li)) {
            final int alpha = frontAlpha(g, gx + (len - 1) * ux, gz + (len - 1) * uz);
            if (alpha > 0) {
                emitCap(ax, az, ux, uz, lx, lz, len - 0.5F, len - 0.25F, 1F, 0F, y(g, gx, gz), light, alpha, out);
                g.lineTexels += CAP_TEX_WIDTH;
                g.lineBlocks += 0.25F;
            }
        }
    }

    /**
     * The film: a thin sheet of water over the sand the wave has flooded, one
     * quad per greedy rectangle. Only {@code filled} cells are covered - the
     * sea itself is vanilla's water. The colour is the local biome water
     * colour, so a swamp shore films brown and a frozen one pale without any
     * per-biome table here.
     */
    private static void emitFilm(final Grid g, final Level level, final Quads out,
                                 final boolean filmDebugColor) {
        final int size = g.size;
        // Cells the front is still crossing: they belong to no rectangle (a
        // greedy merge would lose their fraction, and with it the fade), so they
        // are claimed here and drawn one by one. This is the film's advance -
        // the rest of the sheet is already fully wet and merges as before.
        for (int gz = 0; gz < size; gz++) {
            for (int gx = 0; gx < size; gx++) {
                final int gi = gz * size + gx;
                if (g.filled[gi] != 1 || g.cov[gi] >= 1F || g.cov[gi] <= 0F)
                    continue;
                g.used[gi] = 1;
                if (g.inRenderArea(g.ox + gx, g.oz + gz))
                    emitFilmRect(g, level, gx, gz, 1, 1, out, filmDebugColor);
            }
        }

        for (int gz = 0; gz < size; gz++) {
            for (int gx = 0; gx < size; gx++) {
                final int gi = gz * size + gx;
                if (g.filled[gi] != 1 || g.used[gi] == 1 || !g.inRenderArea(g.ox + gx, g.oz + gz))
                    continue;
                int w = 1;
                while (gx + w < size && g.filled[gi + w] == 1 && g.used[gi + w] == 0
                        && g.inRenderArea(g.ox + gx + w, g.oz + gz))
                    w++;
                int h = 1;
                grow:
                while (gz + h < size) {
                    for (int k = 0; k < w; k++) {
                        final int gj = (gz + h) * size + gx + k;
                        if (g.filled[gj] != 1 || g.used[gj] == 1
                                || !g.inRenderArea(g.ox + gx + k, g.oz + gz + h))
                            break grow;
                    }
                    h++;
                }
                for (int dz = 0; dz < h; dz++)
                    for (int dx = 0; dx < w; dx++)
                        g.used[(gz + dz) * size + gx + dx] = 1;
                emitFilmRect(g, level, gx, gz, w, h, out, filmDebugColor);
            }
        }
    }

    private static void emitFilmRect(final Grid g, final Level level,
                                     final int gx, final int gz, final int w, final int h,
                                     final Quads out, final boolean filmDebugColor) {
        int alpha = 255;
        for (int dz = 0; dz < h; dz++)
            for (int dx = 0; dx < w; dx++)
                alpha = Math.min(alpha, frontAlpha(g, gx + dx, gz + dz));
        if (alpha == 0)
            return;
        // The greedy rectangle is laid out as tiles no larger than
        // {@link #MAX_QUAD_SPAN}: one 7x22 quad was measured on a real shore, and
        // a single quad that size is both the shape of the "one big plate"
        // report and the one thing the geometric self-check cannot admit. The
        // sheet is flat, single-coloured, at one height and one alpha, so the
        // tiling is a pure re-tessellation - the same pixels, more quads.
        for (int tz = 0; tz < h; tz += MAX_QUAD_SPAN) {
            final int th = Math.min(MAX_QUAD_SPAN, h - tz);
            for (int tx = 0; tx < w; tx += MAX_QUAD_SPAN) {
                final int tw = Math.min(MAX_QUAD_SPAN, w - tx);
                final int x = g.ox + gx + tx;
                final int z = g.oz + gz + tz;
                final int cx = x + tw / 2;
                final int cz = z + th / 2;
                final ShoreQuad q = out.next();
                q.tex = TEX_FILM;
                // Every filled cell is beach, so one height covers the tile.
                q.y = surfaceBase(g, gx + tx, gz + tz) + FILM_LIFT;
                q.light = lightAt(level, g, cx, cz);
                // The film is the mirror of the foam: its 16x16 texture is pure
                // white, so the colour has to come from here - the local biome
                // water colour (ocean / deep_ocean / beach / stony_shore are all
                // #3F76E4). The biome water colour scaled exactly as vanilla's
                // water texture scales it, so the film and the sea are the same
                // paint at the same alpha.
                // shoreFilmDebugColor replaces the paint, not the shape: a
                // magenta film that still fades along the front says the vertex
                // colour arrived and only its value is in question.
                q.rgb = filmDebugColor
                        ? FILM_DEBUG_RGB
                        : scaleRgb(BiomeColors.getAverageWaterColor(level,
                                CURSOR.set(cx, g.waterTop + 1, cz)) & 0xFFFFFF, WATER_TINT_SCALE);
                q.alpha = (int) (alpha * FILM_ALPHA);
                // UV density, design gauge: 16x16 sheet, one texel = 1/16 block,
                // so a rect of w blocks spans w in u. The sheet is a single
                // colour today, so this cannot change a pixel - it is here so the
                // density is right by construction if the film ever gains grain,
                // instead of silently collapsing to 16/w texels per block on the
                // large merged rectangles.
                g.filmTexels += (float) (tw + th) * FILM_TEX_WIDTH * 0.5F;
                g.filmBlocks += tw + th;
                g.filmQuads++;
                q.wx[0] = x;        q.wz[0] = z;        q.u[0] = 0F;  q.v[0] = 0F;
                q.wx[1] = x + tw;   q.wz[1] = z;        q.u[1] = tw;  q.v[1] = 0F;
                q.wx[2] = x + tw;   q.wz[2] = z + th;   q.u[2] = tw;  q.v[2] = th;
                q.wx[3] = x;        q.wz[3] = z + th;   q.u[3] = 0F;  q.v[3] = th;
            }
        }
    }

    /**
     * Opacity of the flood film, 0..1.
     *
     * <p><b>180/255 is not a taste knob either.</b> It is the alpha vanilla's
     * water texture carries, so a film drawn at this alpha over a background is
     * <em>bit-identical</em> to the water surface drawn over the same
     * background: same paint ({@link #WATER_TINT_SCALE}), same alpha. Raise it
     * and the wet sand the film is supposed to be lying on stops showing
     * through; lower it and the film stops matching the sea it runs into.
     * The 0.70 this replaced happened to sit within 0.6% of the right number -
     * the colour was the whole defect.</p>
     */
    private static final float FILM_ALPHA = 180F / 255F;

    /**
     * Alpha for a cell: 0 in the unstable margin ring, fading in over
     * {@link #FADE_BLOCKS} blocks so the scan window's edge reads as distance,
     * not as a guillotine.
     */
    private static int edgeAlpha(final Grid g, final int gx, final int gz) {
        final int d = Math.min(Math.min(gx, gz), Math.min(g.size - 1 - gx, g.size - 1 - gz));
        final int t = d - RENDER_MARGIN;
        if (t >= FADE_BLOCKS)
            return 255;
        if (t <= 0)
            return EDGE_FLOOR_ALPHA;
        return EDGE_FLOOR_ALPHA + t * (255 - EDGE_FLOOR_ALPHA) / FADE_BLOCKS;
    }

    /**
     * {@link #edgeAlpha} scaled by how far the front has crossed this cell.
     * Cells the sea already owns get the full value - only land the wave is
     * currently crossing is partial. This is what turns the steppy advance into
     * a fade: a cell the front has half crossed draws at half opacity, so the
     * line never has to decide which side of a block boundary it is on.
     */
    private static int frontAlpha(final Grid g, final int gx, final int gz) {
        final int a = edgeAlpha(g, gx, gz);
        if (a <= 0)
            return 0;
        final int gi = gz * g.size + gx;
        if (g.filled[gi] != 1)
            return a;
        final float c = g.cov[gi];
        return c >= 1F ? a : Math.max(1, (int) (a * c));
    }

    /**
     * A cap is a quarter-block sliver of band that fades out along the shore, so
     * a line that stops - at a corner of the window, or at the end of a spit -
     * tapers instead of ending in a wall. The tile's opaque column is at
     * {@code u = 1}, so {@code uAtA0/uAtA1} put that column on whichever end
     * touches the body; the far cap passes them swapped, which mirrors the tile.
     */
    private static void emitCap(final float ax, final float az,
                                final int ux, final int uz, final int lx, final int lz,
                                final float a0, final float a1,
                                final float uAtA0, final float uAtA1,
                                final float y, final int light, final int alpha, final Quads out) {
        final ShoreQuad q = out.next();
        q.tex = TEX_CAP;
        q.y = y;
        q.light = light;
        q.rgb = FOAM_RGB;
        q.alpha = alpha;
        put(q, 0, ax, az, ux, uz, lx, lz, a0, 0F, uAtA0);
        put(q, 1, ax, az, ux, uz, lx, lz, a1, 0F, uAtA1);
        put(q, 2, ax, az, ux, uz, lx, lz, a1, 1F, uAtA1);
        put(q, 3, ax, az, ux, uz, lx, lz, a0, 1F, uAtA0);
    }

    private static void emitCorner(final Grid g, final Level level, final int gx, final int gz,
                                   final boolean convex, final int landCorner, final Quads out) {
        final int x = g.ox + gx;
        final int z = g.oz + gz;
        // Both arms of the corner have their own phase; average them rather than
        // picking one, so neither arm jumps at the joint.
        final int w = (WAVE[Math.floorMod(x, 64)] + WAVE[Math.floorMod(z, 64)] + 1) >> 1;
        final int slot = (convex ? TEX_CONVEX : TEX_CONCAVE) + (w < 0 ? 0 : w > 3 ? 3 : w);

        // One 16x16 tile across one cell: the same 16 texels per block again,
        // which is why the corner tiles read at the same grain as the strip.
        g.lineTexels += CORNER_TEX_WIDTH;
        g.lineBlocks += 1F;

        final ShoreQuad q = out.next();
        q.tex = slot;
        q.y = surfaceBase(g, gx, gz) + FOAM_LIFT;
        q.light = lightAt(level, g, x, z);
        q.rgb = FOAM_RGB;
        q.alpha = frontAlpha(g, gx, gz);

        // Cell corners: 0 NW, 1 NE, 2 SE, 3 SW. The tile's land sits at its own
        // UV origin, so rotating means handing corner i the UV of corner i - j.
        putCorner(q, 0, x, z, landCorner);
        putCorner(q, 1, x, z, landCorner);
        putCorner(q, 2, x, z, landCorner);
        putCorner(q, 3, x, z, landCorner);
    }

    private static void putCorner(final ShoreQuad q, final int i, final int x, final int z, final int landCorner) {
        // World position of cell corner i.
        final float wx = x + ((i == 1 || i == 2) ? 1F : 0F);
        final float wz = z + (i >= 2 ? 1F : 0F);
        final int uvIdx = Math.floorMod(i - landCorner, 4);
        q.wx[i] = wx;
        q.wz[i] = wz;
        q.u[i] = CORNER_UV[uvIdx][0];
        q.v[i] = CORNER_UV[uvIdx][1];
    }

    /**
     * Places one corner. {@code along} is the offset from the cell centre along
     * the shore axis, {@code v} 0 at the land edge and 1 at the water edge, so
     * the band always grows away from the beach.
     */
    private static void put(final ShoreQuad q, final int i, final float ax, final float az,
                            final int ux, final int uz, final int lx, final int lz,
                            final float along, final float v, final float u) {
        final float off = 0.5F - v;
        q.wx[i] = ax + along * ux + off * lx;
        q.wz[i] = az + along * uz + off * lz;
        q.u[i] = u;
        q.v[i] = v;
    }

    /**
     * Surface height without any lift: open water at {@code waterTop + 8/9},
     * anything the wave has flooded (wet sand) one block higher. Wet and dry
     * cells along one strip differ by exactly this step, which is why strips
     * are cut where it changes.
     */
    private static float surfaceBase(final Grid g, final int gx, final int gz) {
        final byte c = g.cls[gz * g.size + gx];
        return c == CLS_SEA ? g.waterTop + 8F / 9F : g.waterTop + 1F;
    }

    // =====================================================================
    // The maintainer's design - SPEC §10.1 items 1, 2 and 3
    // =====================================================================
    //
    // ONE direction for the whole window. Whichever way this coast actually runs
    // is chosen by counting edges; runs parallel to it draw the band; runs across
    // it connect and NEVER draw a band of their own.
    //
    // That last rule is the whole design and it is what the earlier per-cell
    // version could not honour. Judging each cell's own direction means the two
    // Runs that start at the same sea cell both emit, so one stretch of coast gets
    // its band twice and the two copies cross instead of joining - which is the
    // "everything slanted, the perpendicular ones spawn waves of their own"
    // report. A single global direction removes the choice, so the two copies
    // cannot both be along it.
    //
    // Depth is per column: how far inland this column's beach runs before it hits
    // a cell one block higher, times the swell's progress. Neighbouring columns
    // differ, so the band edge is a staircase. That is the wanted shape - a
    // staircase is axis-aligned. The thing that read as "slanted" before was a
    // straight line drawn between two columns of different depth, which is a
    // different mistake and is not what this does.

    /** One cell edge of the coast: which way it runs, which way is inland, how deep. */
    private static final class ShoreEdge {
        final int x0, z0, x1, z1;
        /** Inland: one of the four DIR vectors. */
        final int dx, dz;
        /** Beach depth inland of this edge in blocks - the maintainer's d. */
        final int depth;
        /** True when this edge runs along the window's chosen main direction. */
        boolean along;

        ShoreEdge(final int x0, final int z0, final int x1, final int z1,
                  final int dx, final int dz, final int depth) {
            this.x0 = x0;
            this.z0 = z0;
            this.x1 = x1;
            this.z1 = z1;
            this.dx = dx;
            this.dz = dz;
            this.depth = depth;
        }

        /** True when the edge runs along X. */
        boolean isX() {
            return this.z0 == this.z1;
        }

        long key() {
            final long a = ((long) x0 << 32) ^ (z0 & 0xFFFFFFFFL);
            final long b = ((long) x1 << 32) ^ (z1 & 0xFFFFFFFFL);
            return a < b ? (a * 1000003L + b) : (b * 1000003L + a);
        }
    }

    /**
     * Every coast cell edge, once, each carrying its own beach depth.
     *
     * <p>Deduplicated: two Runs meeting at a sea cell describe one edge twice, and
     * without this the band is drawn twice over the same ground - the overlap is
     * what reads as a second wave.</p>
     */
    private static void collectShoreEdges(final Grid g) {
        if (g.shoreEdges.length < g.runCells + 8)
            g.shoreEdges = new ShoreEdge[g.runCells + 8];
        g.shoreEdgeCount = 0;
        g.gridId = System.identityHashCode(g);
        g.shuffle = 0;
        g.jointEmitted = 0;
        g.jointSplit = 0;
        g.jointNoBandA = 0;
        g.jointNoBandB = 0;
        g.jointSameLine = 0;
        g.jointFlat = 0;
        g.jointSampleCount = 0;
        for (final Run r : g.runs) {
            for (int i = 0; i < r.len; i++) {
                final int ax = r.startX + i * r.ux;
                final int az = r.startZ + i * r.uz;
                final ShoreEdge e = new ShoreEdge(ax, az, ax + r.ux, az + r.uz,
                        r.dx, r.dz, r.d[i]);
                final long k = e.key();
                boolean seen = false;
                for (int j = 0; j < g.shoreEdgeCount; j++)
                    if (g.shoreEdges[j].key() == k) {
                        seen = true;
                        break;
                    }
                if (seen)
                    continue;
                if (g.shoreEdgeCount >= g.shoreEdges.length)
                    return;
                g.shoreEdges[g.shoreEdgeCount++] = e;
            }
        }
        // The main direction comes from the coast, not from a constant: whichever
        // orientation has more edges. Read from the terrain it needs no setting and
        // it makes connectors the minority by construction - otherwise they would
        // be the ones drawing bands, which is the thing to avoid.
        int alongX = 0;
        int alongZ = 0;
        for (int i = 0; i < g.shoreEdgeCount; i++) {
            if (g.shoreEdges[i].isX())
                alongX++;
            else
                alongZ++;
        }
        // It used to be whichever way had ONE more edge. The window is centred on the
        // player, so on a coast that is anywhere near balanced - an L, a spit, a beach
        // running diagonally - the counts swap as he walks and the whole picture swaps
        // with them: every band becomes a joint and every joint a band. That is the
        // "verticals keep appearing and disappearing depending on where I stand and
        // which way I look". Require a margin before changing direction; near a tie,
        // keep what we had.
        if (alongX >= alongZ + MAIN_DIR_MARGIN)
            g.mainAlongX = true;
        else if (alongZ >= alongX + MAIN_DIR_MARGIN)
            g.mainAlongX = false;
        else
            g.mainAlongX = lastMainAlongX;
        lastMainAlongX = g.mainAlongX;
        g.edgeX = alongX;
        g.edgeZ = alongZ;
        g.shuffle = 1; // reached the tail: along flags are assigned
        for (int i = 0; i < g.shoreEdgeCount; i++)
            g.shoreEdges[i].along = g.shoreEdges[i].isX() == g.mainAlongX;
    }

    /**
     * The band, under the maintainer's design.
     *
     * <p>Two passes, and the order is the design rather than a detail: every
     * main-direction edge first, then the cross-direction edges as connectors.
     * A connector is only ever emitted between two points that main-direction
     * edges already reached, so it can join a coast but can never start one.</p>
     */
    private static void emitShoreLine(final Grid g, final Level level, final float p, final Quads out) {
        // A coastline with no edges means the collection step did not run, not that
        // the coast is empty: the scan reports dozens of runs every tick. The first
        // version of this method read the edge list without collecting it, and the
        // symptom was "no waves at all" with no error anywhere - the loop simply
        // had nothing to iterate. Thrown rather than warned because this class has
        // no logger, and the caller already isolates and reports build failures, so
        // it reaches the log with a stack instead of vanishing.
        if (g.shoreEdgeCount == 0)
            throw new IllegalStateException("[ShoreWave] fold line: 0 coast edges from "
                    + g.runs.size() + " runs - collection did not run");
        // Pass 1: the bands - main-direction edges only, each placed by ITS OWN inland
        // direction and depth. Summing the normals of whatever edges meet at a point was
        // tried and is unsafe: where the coast is a one-cell spit the normals cancel, the
        // mitre length 2w/|s| blows up, and the shore becomes a few twisted sheets while
        // the ordinary bands are dropped by the span audit. Per-edge placement cannot do
        // that - the offset is always exactly one beach depth in one direction.
        for (int i = 0; i < g.shoreEdgeCount; i++) {
            final ShoreEdge e = g.shoreEdges[i];
            if (!e.along)
                continue;
            final float depth = Math.min(e.depth, RUNUP_MAX) * p;
            if (depth <= 0.001F)
                continue;
            emitShoreBand(g, level, out, e, depth);
        }
        // Pass 2: a cross-direction edge is never a wave of its own - it may only appear
        // as a joint between two bands, placed on the bands' own corners so both ends meet.
        for (int i = 0; i < g.shoreEdgeCount; i++) {
            final ShoreEdge e = g.shoreEdges[i];
            if (e.along)
                continue;
            emitShoreConnector(g, level, out, e, p);
        }
    }



    /** One band quad: this edge, offset inland from the waterline by the line's own travel. */
    /** One band quad: this edge, from the coastline inland by {@code depth}. */
    private static void emitShoreBand(final Grid g, final Level level, final Quads out,
                               final ShoreEdge e, final float depth) {
        final int gx = e.x0 - g.ox + (depth >= 1F ? e.dx : 0);
        final int gz = e.z0 - g.oz + (depth >= 1F ? e.dz : 0);
        final float x0 = e.x0 + depth * e.dx;
        final float z0 = e.z0 + depth * e.dz;
        final float x1 = e.x1 + depth * e.dx;
        final float z1 = e.z1 + depth * e.dz;
        emitShoreQuad(g, level, out, x0, z0, x1, z1, e, e.dx, e.dz, gx, gz);
    }

    /**
     * One strip quad. The inland direction is forced perpendicular to the baseline: an
     * edge whose carried inland vector runs parallel to its own baseline builds a
     * zero-area quad - submitted, counted everywhere, invisible.
     */
    private static void emitShoreQuad(final Grid g, final Level level, final Quads out,
                               final float x0, final float z0, final float x1, final float z1,
                               final ShoreEdge e, final int inlandX, final int inlandZ,
                               final int gx, final int gz) {
        final ShoreQuad q = out.next();
        q.tex = TEX_STRIP;
        q.y = surfaceBase(g, gx, gz) + FOAM_LIFT;
        q.light = lightAt(level, g, gx, gz);
        q.rgb = FOAM_RGB;
        q.alpha = 255;
        final float seg = (float) Math.hypot(x1 - x0, z1 - z0);
        // Each quad shows the same slice of the tile (u 0..len/PERIOD). Mapping u from the
        // world position instead made every quad sample a different part of a tile that has
        // transparent cells by design, and the line came out as scattered dashes.
        q.u[0] = 0F;
        q.u[1] = seg / STRIP_PERIOD - (float) Math.floor(seg / STRIP_PERIOD);
        q.u[2] = q.u[1];
        q.u[3] = q.u[0];
        final int ix = inlandPerp(x0, z0, x1, z1, inlandX, inlandZ) ? INLAND[0] : inlandX;
        final int iz = inlandPerp(x0, z0, x1, z1, inlandX, inlandZ) ? INLAND[1] : inlandZ;
        // v: the DIRECTION was right all along - the art reads crest (row 0, white) at the
        // inland edge and dark tail (row 11) toward the sea, which is a swash: bright where
        // the wash runs out on the sand, dark where it drains back. The bug was the RANGE:
        // the baseline sat at 1.0, so rows 12-15 - measured fully transparent - were part
        // of the band and a third of it drew nothing at all. 0.75 stops at the last
        // visible row; the art keeps its direction.
        q.wx[0] = x0;                      q.wz[0] = z0;                      q.v[0] = 0.75F;
        q.wx[1] = x1;                      q.wz[1] = z1;                      q.v[1] = 0.75F;
        q.wx[2] = x1 + BAND_WIDTH * ix;    q.wz[2] = z1 + BAND_WIDTH * iz;    q.v[2] = 0F;
        q.wx[3] = x0 + BAND_WIDTH * ix;    q.wz[3] = z0 + BAND_WIDTH * iz;    q.v[3] = 0F;
        g.lineTexels += seg * STRIP_TEX_WIDTH;
        g.lineBlocks += seg;
        g.stripQuads++;
    }



    /** Scratch for {@link #inlandPerp}: {x, z}. Build is single threaded. */
    private static final int[] INLAND = new int[2];

    /**
     * The inland direction, forced perpendicular to the baseline.
     *
     * @return {@code true} when {x, z} may be read from {@link #INLAND}
     */
    private static boolean inlandPerp(final float x0, final float z0, final float x1, final float z1,
                                      final int inlandX, final int inlandZ) {
        final int ex = x1 > x0 ? 1 : (x1 < x0 ? -1 : 0);
        final int ez = z1 > z0 ? 1 : (z1 < z0 ? -1 : 0);
        if (ex == 0 && ez == 0)
            return false;
        if (inlandX * ex + inlandZ * ez != 0) {
            final int ax = -ez, az = ex;
            if (ax * inlandX + az * inlandZ >= 0) {
                INLAND[0] = ax;
                INLAND[1] = az;
            } else {
                INLAND[0] = ez;
                INLAND[1] = -ex;
            }
        } else {
            INLAND[0] = inlandX;
            INLAND[1] = inlandZ;
        }
        return true;
    }













    /**
     * How many more edges one orientation must have before the window's main direction
     * switches to it. Without it a near-tie flips on every recount - see
     * {@link #collectShoreEdges}.
     */
    private static final int MAIN_DIR_MARGIN = 2;
    /** The main direction of the previous build, held across builds for stability. */
    private static boolean lastMainAlongX = true;

    /**
     * How far along its own axis a connector will look for the band it joins. Two, not
     * one: on a stepped coast the two lines a joint bridges are often a cell further
     * apart than the joint itself is long, and at one the search walked past both of
     * them. Measured on the six synthetic coasts, two raises the joints from 15 to 19
     * and costs none of the ones one already found.
     */
    private static final int CONNECTOR_TOLERANCE = 2;

    /** Scratch for {@link #nearestBandEnd}: the band found, and which corner of it. */
    private static ShoreEdge jointBand;
    private static int jointX;
    private static int jointZ;
    /** A corner the search must skip: see {@link #nearestBandEnd}. */
    private static boolean jointSkip;
    private static int jointSkipX;
    private static int jointSkipZ;

    /**
     * The nearest main-direction band corner to {@code (x, z)}, looking along
     * {@code (ux, uz)} out to {@link #CONNECTOR_TOLERANCE} cells either way. The band
     * lands in {@link #jointBand} and its corner in {@link #jointX}/{@link #jointZ}.
     *
     * <p>Two things here are what make a joint actually appear.</p>
     *
     * <p><b>The corner comes back, not just the band.</b> The joint's end has to be
     * placed ON the band - the two must share that exact point, or the joint leaves a
     * notch where it should meet. Placing it on the cross edge's own endpoint instead
     * is only the same thing when the match is exact, which is why the old code looked
     * right on a staircase and wrong everywhere else.</p>
     *
     * <p><b>{@code exclude} keeps the two ends apart.</b> At a one-cell step both ends
     * of the joint are within tolerance of ONE line, and the old rule - find a band at
     * each end, then reject the joint if they are the same band - threw those away.
     * That is the whole of "stepped coasts have no verticals at all": the joint was
     * there, it was the rejection that removed it. Asking the second end for a DIFFERENT
     * band gets the step the two lines it is supposed to bridge.</p>
     */
    private static boolean nearestBandEnd(final Grid g, final int x, final int z,
                                          final int ux, final int uz, final ShoreEdge exclude) {
        for (int k = 0; k <= CONNECTOR_TOLERANCE; k++) {
            for (int s = -1; s <= 1; s += 2) {
                if (k == 0 && s < 0)
                    continue;
                final int px = x + ux * k * s;
                final int pz = z + uz * k * s;
                for (int i = 0; i < g.shoreEdgeCount; i++) {
                    final ShoreEdge e = g.shoreEdges[i];
                    if (!e.along || e == exclude)
                        continue;
                    // Two bands share a corner wherever the coast has two edges in a
                    // row - (7,12)-(7,13) and (7,13)-(7,14) both own (7,13). Excluding
                    // the band is not enough: the second end then finds the OTHER band
                    // at the SAME corner and the joint comes out zero long, which is a
                    // quad that is submitted, counted, and invisible. Skip the corner.
                    if (jointSkip && px == jointSkipX && pz == jointSkipZ)
                        continue;
                    if (e.x0 == px && e.z0 == pz) {
                        jointBand = e;
                        jointX = e.x0;
                        jointZ = e.z0;
                        return true;
                    }
                    if (e.x1 == px && e.z1 == pz) {
                        jointBand = e;
                        jointX = e.x1;
                        jointZ = e.z1;
                        return true;
                    }
                }
            }
        }
        jointBand = null;
        return false;
    }

    /**
     * A joint: drawn ONLY where both ends touch a band, so a cross-direction edge can never
     * become a wave of its own. Each end is placed on ITS OWN band - that band's depth along
     * that band's inland direction - and the width runs perpendicular to the joint's own
     * baseline; borrowing the bands' inland direction for the width is what collapsed these
     * quads to a line (four corners sharing one coordinate: submitted, counted, invisible).
     */
    private static void emitShoreConnector(final Grid g, final Level level, final Quads out,
                                           final ShoreEdge e, final float p) {
        final int cx = Integer.signum(e.x1 - e.x0);
        final int cz = Integer.signum(e.z1 - e.z0);
        jointSkip = false;
        if (!nearestBandEnd(g, e.x0, e.z0, cx, cz, null)) {
            g.jointNoBandA++;
            return;
        }
        final ShoreEdge b0 = jointBand;
        final int jx0 = jointX;
        final int jz0 = jointZ;
        // The other end must land on a DIFFERENT band at a DIFFERENT corner - see
        // nearestBandEnd. With no second band there is no joint, and a cross-direction
        // edge must never become a wave of its own.
        jointSkip = true;
        jointSkipX = jx0;
        jointSkipZ = jz0;
        final boolean found = nearestBandEnd(g, e.x1, e.z1, cx, cz, b0);
        jointSkip = false;
        if (!found) {
            // Either nothing that far, or only the one line the first end already took.
            // The two are told apart by a second, exclusion-free probe.
            g.jointSameLine = nearestBandEnd(g, e.x1, e.z1, cx, cz, null) ? 1 : 0;
            g.jointNoBandB++;
            return;
        }
        final ShoreEdge b1 = jointBand;
        final int jx1 = jointX;
        final int jz1 = jointZ;
        // The joint spans the gap between the two lines as they are placed right now:
        // its ends ARE those lines' positions, so it meets both of them however far apart
        // the swell has moved them, and its length is whatever that gap happens to be -
        // not a whole number of tiles. The tile is laid on by arc length, so a fractional
        // length is simply a fractional piece of the same tile rather than a stretched one.
        final float d0 = Math.min(b0.depth, RUNUP_MAX) * p;
        final float d1 = Math.min(b1.depth, RUNUP_MAX) * p;
        if (d0 <= 0.001F && d1 <= 0.001F) {
            g.jointFlat++;
            return;
        }
        int ix = e.dx;
        int iz = e.dz;
        if (ix * cx + iz * cz != 0) {
            final int px = -cz;
            final int pz = cx;
            if (px * e.dx + pz * e.dz >= 0) {
                ix = px;
                iz = pz;
            } else {
                ix = cz;
                iz = -cx;
            }
        }
        // Each end sits on its OWN band's surface. A band is drawn at the water plane
        // while it is still out over the sea and lifts onto the flooded sand once it has
        // climbed a block - emitShoreBand moves its sample cell inland for exactly that.
        // A joint drawn at ONE height cannot follow both, and at the lower of the two its
        // inland end is inside the sand: the "verticals are buried" report. Take the
        // height each band is actually drawn at, and where they differ cut the joint in
        // two so each half lies on the surface its own end is on.
        final float y0 = bandSurfaceY(g, b0, d0);
        final float y1 = bandSurfaceY(g, b1, d1);
        // Half a band width further inland, because a band is drawn from its baseline
        // OUT to baseline + width: its visible middle is half a width in. A joint that ran
        // baseline to baseline stopped half a width short on the far side and left the
        // outer corner of the turn uncovered - the "there's a gap where the vertical
        // meets" report. Both ends move by the same half width, so the joint's length is
        // unchanged; it just sits where the ribbon actually is.
        // A band is a ribbon of width BAND_WIDTH swept along the shore. Where two bands
        // step sideways, the RIBBON's centre line steps with them - and a ribbon that
        // steps sideways has to travel the step DIAGONALLY, not as a flat horizontal
        // piece: a flat piece's own cross-section runs the wrong way, which is why the
        // gradient never met the bands' ends and the two hard cuts showed as notches
        // (the maintainer circled exactly those).
        //
        // So the joint is the same ribbon, sheared: its start cross-section IS band A's
        // cross-section, its end cross-section IS band B's, each taken half a width back
        // from the centre line (the bands draw one-sided: baseline -> baseline + width)
        // and pushed half a width along the shore so the two meet with something to blend
        // through. u/v then run exactly as they do on a band - v across, u along - and no
        // corner art is needed to hide anything.
        final float half = BAND_WIDTH * 0.5F;
        final float run = BAND_WIDTH * 0.5F;
        final float px = -cz;
        final float pz = cx;
        final float aOx = jx0 + d0 * b0.dx - half * b0.dx - px * run;
        final float aOz = jz0 + d0 * b0.dz - half * b0.dz - pz * run;
        final float bOx = jx1 + d1 * b1.dx - half * b1.dx + px * run;
        final float bOz = jz1 + d1 * b1.dz - half * b1.dz + pz * run;
        final int gx0 = b0.x0 - g.ox + (d0 >= 1F ? b0.dx : 0);
        final int gz0 = b0.z0 - g.oz + (d0 >= 1F ? b0.dz : 0);
        final int gx1 = b1.x0 - g.ox + (d1 >= 1F ? b1.dx : 0);
        final int gz1 = b1.z0 - g.oz + (d1 >= 1F ? b1.dz : 0);
        g.jointEmitted++;
        if (y0 != y1)
            g.jointSplit++;
        if (g.jointSampleCount < Grid.JOINT_SAMPLE) {
            final int o6 = g.jointSampleCount * 8;
            final int o4 = g.jointSampleCount * 4;
            g.jointInts[o6] = e.x0;
            g.jointInts[o6 + 1] = e.z0;
            g.jointInts[o6 + 2] = e.x1;
            g.jointInts[o6 + 3] = e.z1;
            g.jointInts[o6 + 4] = jx0;
            g.jointInts[o6 + 5] = jz0;
            g.jointInts[o6 + 6] = jx1;
            g.jointInts[o6 + 7] = jz1;
            g.jointFloats[o4] = aOx;
            g.jointFloats[o4 + 1] = aOz;
            g.jointFloats[o4 + 2] = bOx;
            g.jointFloats[o4 + 3] = bOz;
            g.jointSampleCount++;
        }
        emitConnectorQuad(g, level, out,
                aOx, aOz,
                aOx + BAND_WIDTH * b0.dx, aOz + BAND_WIDTH * b0.dz,
                bOx + BAND_WIDTH * b1.dx, bOz + BAND_WIDTH * b1.dz,
                bOx, bOz, y0, gx0, gz0);
    }

    /**
     * The joint quad: baseline between the two bands' corners, width perpendicular to it.
     *
     * <p>{@code y} is passed in rather than sampled here. Sampling it at the cross edge's
     * own cell is what buried the joints: that cell is open water, so the quad sat at the
     * water plane while its two ends were up on the flooded sand a ninth of a block
     * higher - entirely inside the beach. The caller knows which surface each end is on.</p>
     */
    private static void emitConnectorQuad(final Grid g, final Level level, final Quads out,
                                          final float x0, final float z0, final float x1, final float z1,
                                          final float x2, final float z2, final float x3, final float z3,
                                          final float y, final int gx, final int gz) {
        final ShoreQuad q = out.next();
        q.tex = TEX_STRIP;
        q.y = y;
        q.light = lightAt(level, g, gx, gz);
        q.rgb = FOAM_RGB;
        q.alpha = 255;
        // Corners 0/1 are the start cross-section (water side, inland side) and 2/3 the
        // end one, so v runs ACROSS the ribbon exactly as on a band and u runs along it.
        // The gradient therefore points the same way at both ends - that is the whole fix.
        final float seg = (float) Math.hypot(x2 - x0, z2 - z0);
        final float uu = seg / STRIP_PERIOD - (float) Math.floor(seg / STRIP_PERIOD);
        q.wx[0] = x0;      q.wz[0] = z0;      q.v[0] = 0.75F;
        q.wx[1] = x1;      q.wz[1] = z1;      q.v[1] = 0F;
        q.wx[2] = x2;      q.wz[2] = z2;      q.v[2] = 0F;
        q.wx[3] = x3;      q.wz[3] = z3;      q.v[3] = 0.75F;
        q.u[0] = 0F;
        q.u[1] = uu;
        q.u[2] = uu;
        q.u[3] = 0F;
        g.lineTexels += seg * STRIP_TEX_WIDTH;
        g.lineBlocks += seg;
        g.stripQuads++;
    }

    /** The cell class at a world position - for the joint diagnostic line. */
    public static String cellName(final Grid g, final float wx, final float wz) {
        final int gx = (int) Math.floor(wx) - g.ox;
        final int gz = (int) Math.floor(wz) - g.oz;
        if (gx < 0 || gz < 0 || gx >= g.size || gz >= g.size)
            return "OUT";
        return switch (g.cls[gz * g.size + gx]) {
            case CLS_SEA -> "SEA";
            case CLS_BEACH -> "BEACH";
            case CLS_HIGH -> "HIGH";
            default -> "UNKNOWN";
        };
    }

    /** Foam height: the cell's own surface plus the foam lift. */
    private static float y(final Grid g, final int gx, final int gz) {
        return surfaceBase(g, gx, gz) + FOAM_LIFT;
    }

    /**
     * The height {@link #emitShoreBand} draws a band at - the SAME expression, cell and
     * all. A joint has to be told this per end rather than working it out from its own
     * cell, because the two ends are usually on different surfaces.
     */
    private static float bandSurfaceY(final Grid g, final ShoreEdge b, final float depth) {
        final int gx = b.x0 - g.ox + (depth >= 1F ? b.dx : 0);
        final int gz = b.z0 - g.oz + (depth >= 1F ? b.dz : 0);
        return surfaceBase(g, gx, gz) + FOAM_LIFT;
    }

    private static int lightAt(final Level level, final Grid g, final int x, final int z) {
        // Offline there is no world to ask. The offline simulator drives this very code
        // (see simulate) and does not care about light, so hand back full bright rather
        // than throwing - the geometry it is there to measure is unaffected.
        if (level == null)
            return 0xF000F0;
        return LevelRenderer.getLightColor(level, CURSOR.set(x, g.waterTop + 1, z));
    }

    /**
     * Java's {@code Math.round} is {@code floor(x + 0.5)}; Python's {@code round}
     * is banker's rounding. The twin has to use the same one or a smooth front
     * measures as sawtooth.
     *
     * <p>Kept although the front no longer rounds: the offline twin still needs
     * it to reproduce the old integer behaviour when comparing, and it is the
     * reason that change was measured rather than guessed.</p>
     */
    @SuppressWarnings("unused")
    private static int jround(final float x) {
        return (int) Math.floor(x + 0.5);
    }

